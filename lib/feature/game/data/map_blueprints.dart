/// 맵 원본 데이터. data 계층의 표현이며 도메인 `GameMap` 과 분리한다.
///
/// 파싱은 `MapParser` 가 맡는다.
class MapBlueprint {
  const MapBlueprint({required this.levelNumber, required this.rows});

  /// 대응하는 레벨 번호. `kLevels` 와 이 값으로 조인된다.
  final int levelNumber;

  /// ASCII 격자. 표기는 기획서 §9.1 — 칸과 경계를 번갈아 적는 `2N+1` 격자다.
  ///
  /// 칸(홀·홀)     `.` 빈칸 · `#` 칸 벽 · `G` 목표 · `X` 블랙홀 · `@` 플레이어 · `O` 일반 블록
  /// 세로 경계(홀·짝) `|` 벽 / 공백 없음
  /// 가로 경계(짝·홀) `-` 벽 / 공백 없음
  /// 교차점(짝·짝)   `+`
  final List<String> rows;
}

