/// 칸의 **바닥** 종류. 레벨이 시작된 뒤로는 바뀌지 않는다.
///
/// 칸은 `바닥 + 내용물`로 모델링한다(기획서 §2.2). 내용물은 [Block] 이 담당한다.
/// 목표 칸 위에 블록이 얹힌 상태, 블랙홀 위를 블록이 지나가는 상태를 모두
/// 표현해야 하므로 단일 enum 하나로 칸을 표현하지 않는다.
enum FloorType {
  /// 빈 칸. 통과 가능.
  empty,

  /// 벽. 통과 불가. 블록은 벽 직전에 멈춘다.
  wall,

  /// 목표 지점. 통과 가능한 바닥 표시일 뿐이며, 플레이어가 **멈췄을 때만** 클리어다.
  goal,

  /// 블랙홀. 지나가는 블록은 빨려 들어가 사라진다. 블랙홀 자체는 소모되지 않는다.
  ///
  /// **맵 기호는 `X` 그대로다** (기획서 §2.2) — 이름만 바뀌었다.
  blackHole,
}
