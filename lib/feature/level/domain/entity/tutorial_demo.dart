/// 레벨이 처음 가르치는 규칙 (13-game-feel §6).
///
/// 튜토리얼 문구 위에서 이 장면이 반복 재생된다. **어느 레벨이 무엇을
/// 가르치는지는 번역이 아니라 레벨 설계의 사실**이라 문구(`AppStrings`)가
/// 아니라 레벨 데이터가 갖는다 — `11` 에서 `hasTutorial` 을 만든 이유와 같다.
///
/// **`level` 이 갖되 그림은 `game` 이 그린다.** 여기 있는 것은 "무엇을
/// 가르치는가" 라는 이름뿐이고 판도 좌표도 없다. 판을 담으면 `level → game`
/// 순환이 되살아난다.
enum TutorialDemo {
  /// 블록은 벽이나 판 끝에 닿을 때까지 미끄러진다.
  slide,

  /// 동료 블록이 발판이 되어 플레이어를 멈춰 세운다.
  ///
  /// **이름은 `blockBrake` 그대로다.** 화면에 나가는 말은 `동료 블록`·`발판` 으로
  /// 통일했지만(#126), 열거자 이름은 저장된 값이 아니라 코드 식별자일 뿐이라
  /// 바꿔서 얻는 것이 없다.
  blockBrake,

  /// 블랙홀은 지나가기만 해도 빨아들인다.
  blackHole,

  /// 경계 벽은 통행만 막고 양쪽 칸은 살아 있다.
  edgeWall,
}
